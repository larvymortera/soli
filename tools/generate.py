#!/usr/bin/env python3
"""Generate installable ports from shared palettes using only Python's stdlib."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI = ('bg', 'surface', 'panel', 'selection', 'accent', 'fg', 'muted', 'border')
SCOPES = {
    'comment': 'comment',
    'keyword': 'keyword, storage',
    'string': 'string',
    'number': 'constant.numeric, constant.language',
    'function': 'entity.name.function, support.function',
    'type': 'entity.name.type, entity.name.class, support.type, support.class',
    'error': 'invalid',
}


def load_palettes():
    return [json.loads(p.read_text()) for p in sorted((ROOT / 'palettes').glob('*/*.json'))]


def outputs(palette):
    name, ui, syntax = palette['name'], palette['ui'], palette['syntax']
    tmux = '# Generated by tools/generate.py; edit palettes instead.\n'
    tmux += ''.join(f'{role}={ui[role]}\n' for role in UI)
    yield ROOT / 'ports/tmux/themes' / f'{name}.tmuxtheme', tmux
    variables = dict(ui, **syntax)
    globals_ = {key: f'var({role})' for key, role in {
        'background': 'bg', 'foreground': 'fg', 'caret': 'accent',
        'selection': 'selection', 'selection_foreground': 'fg',
        'line_highlight': 'surface', 'gutter': 'bg', 'gutter_foreground': 'muted',
        'accent': 'accent', 'misspelling': 'error',
        'line_diff_added': 'string', 'line_diff_modified': 'warning',
        'line_diff_deleted': 'error',
    }.items()}
    rules = [{'name': role.title(), 'scope': scope, 'foreground': f'var({role})'}
             for role, scope in SCOPES.items()]
    # Keep selected syntax readable instead of retaining syntax colors over selection.
    scheme = {'name': f'Soli {name.title()}', 'author': 'Soli',
              'variables': variables, 'globals': globals_, 'rules': rules}
    yield ROOT / 'ports/sublime/schemes' / f'Soli {name.title()}.sublime-color-scheme', json.dumps(scheme, indent=2) + '\n'


def generate(check=False):
    expected = dict(output for palette in load_palettes() for output in outputs(palette))
    stale = []
    for path, content in expected.items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    for folder, pattern in [('ports/tmux/themes', '*.tmuxtheme'),
                            ('ports/sublime/schemes', '*.sublime-color-scheme')]:
        stale.extend(str(p.relative_to(ROOT)) for p in (ROOT / folder).glob(pattern) if p not in expected)
    if stale:
        raise ValueError('Missing, stale, or unexpected outputs: ' + ', '.join(stale))
    return len(expected)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check outputs without writing')
    args = parser.parse_args()
    try:
        # Validate before writing any output.
        from validate import validate
        validate()
        print(f'{generate(args.check)} generated files {"checked" if args.check else "written"}.')
    except (ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'{error}\n')
