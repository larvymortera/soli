#!/usr/bin/env python3
"""Generate installable ports from shared palettes using only Python's stdlib."""
import argparse
import json
import plistlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI = ('bg', 'surface', 'panel', 'selection', 'accent', 'fg', 'muted', 'border')
SCOPES = {
    'comment': 'comment',
    'keyword': 'keyword, storage',
    'string': 'string',
    'number': 'constant.numeric, constant.language',
    'function': 'entity.name.function, support.function',
    'type': 'entity.name.type, entity.name.class, support.type, support.class',
    'error': 'invalid',
}


# ANSI indices 0..7 and 8..15 use the same semantic hues. Bright variants
# deliberately reuse source colors rather than inventing unvalidated shades.
ANSI = ('Black', 'Red', 'Green', 'Yellow', 'Blue', 'Magenta', 'Cyan', 'White')
ANSI_ROLES = (('ui', 'bg'), ('syntax', 'error'), ('syntax', 'string'),
              ('syntax', 'warning'), ('syntax', 'type'), ('syntax', 'keyword'),
              ('ui', 'accent'), ('ui', 'fg'))


def terminal_color(color):
    """Encode an opaque calibrated RGB NSColor as a native keyed archive."""
    rgb = ' '.join(format(int(color[i:i + 2], 16) / 255, '.10g')
                   for i in (1, 3, 5)) + ' 1'
    return plistlib.dumps({
        '$archiver': 'NSKeyedArchiver', '$version': 100000,
        '$top': {'root': plistlib.UID(1)},
        '$objects': ['$null', {'$class': plistlib.UID(2), 'NSColorSpace': 1,
                               'NSRGB': rgb.encode('ascii') + b'\0'},
                     {'$classes': ['NSColor', 'NSObject'], '$classname': 'NSColor'}],
    }, fmt=plistlib.FMT_BINARY, sort_keys=True)


def terminal_profile(palette):
    ui = palette['ui']
    profile = {'name': 'Soli ' + palette['name'].title(),
               'type': 'Window Settings', 'ProfileCurrentVersion': 2.09,
               'UseBrightBold': False}
    for key, role in {'BackgroundColor': 'bg', 'TextColor': 'fg',
                      'TextBoldColor': 'fg', 'CursorColor': 'accent',
                      'SelectionColor': 'selection'}.items():
        profile[key] = terminal_color(ui[role])
    for name, (section, role) in zip(ANSI, ANSI_ROLES):
        color = terminal_color(palette[section][role])
        profile['ANSI' + name + 'Color'] = color
        profile['ANSIBright' + name + 'Color'] = color
    # Bright black is secondary text, including on light profiles.
    profile['ANSIBrightBlackColor'] = terminal_color(ui['muted'])
    return plistlib.dumps(profile, sort_keys=True).decode('utf-8')


def codex_theme(palette):
    """Encode a TextMate theme for Codex CLI's syntax highlighter."""
    ui, syntax = palette['ui'], palette['syntax']
    settings = [{'settings': {key: ui[role] for key, role in {
        'background': 'bg', 'foreground': 'fg', 'caret': 'accent',
        'selection': 'selection', 'lineHighlight': 'surface',
        'gutterForeground': 'muted',
    }.items()}}]
    settings.extend({'name': role.title(), 'scope': scope,
                     'settings': {'foreground': syntax[role]}}
                    for role, scope in SCOPES.items())
    settings.extend({'name': name, 'scope': scope,
                     'settings': {'foreground': color}}
                    for name, scope, color in (
                        ('Warning', 'markup.warning', syntax['warning']),
                        ('Inserted', 'markup.inserted', syntax['string']),
                        ('Deleted', 'markup.deleted', syntax['error']),
                        ('Changed', 'markup.changed', syntax['warning'])))
    return plistlib.dumps({
        'name': 'Soli ' + palette['name'].title(),
        'comment': 'Generated by tools/generate.py; edit palettes instead.',
        'settings': settings,
    }, sort_keys=True).decode('utf-8')


def load_palettes():
    return [json.loads(p.read_text()) for p in sorted((ROOT / 'palettes').glob('*/*.json'))]


def outputs(palette):
    name, ui, syntax = palette['name'], palette['ui'], palette['syntax']
    tmux = '# Generated by tools/generate.py; edit palettes instead.\n'
    tmux += ''.join(f'{role}={ui[role]}\n' for role in UI)
    yield ROOT / 'ports/tmux/themes' / f'{name}.tmuxtheme', tmux
    yield ROOT / 'ports/terminal/profiles' / f'Soli {name.title()}.terminal', terminal_profile(palette)
    yield ROOT / 'ports/codex/themes' / f'soli-{name}.tmTheme', codex_theme(palette)
    variables = dict(ui, **syntax)
    globals_ = {key: f'var({role})' for key, role in {
        'background': 'bg', 'foreground': 'fg', 'caret': 'accent',
        'selection': 'selection', 'selection_foreground': 'fg',
        'line_highlight': 'surface', 'gutter': 'bg', 'gutter_foreground': 'muted',
        'accent': 'accent', 'misspelling': 'error',
        'line_diff_added': 'string', 'line_diff_modified': 'warning',
        'line_diff_deleted': 'error',
    }.items()}
    rules = [{'name': role.title(), 'scope': scope, 'foreground': f'var({role})'}
             for role, scope in SCOPES.items()]
    # Keep selected syntax readable instead of retaining syntax colors over selection.
    scheme = {'name': f'Soli {name.title()}', 'author': 'Soli',
              'variables': variables, 'globals': globals_, 'rules': rules}
    yield ROOT / 'ports/sublime/schemes' / f'Soli {name.title()}.sublime-color-scheme', json.dumps(scheme, indent=2) + '\n'


def generate(check=False):
    expected = dict(output for palette in load_palettes() for output in outputs(palette))
    stale = []
    for path, content in expected.items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    for folder, pattern in [('ports/tmux/themes', '*.tmuxtheme'),
                            ('ports/sublime/schemes', '*.sublime-color-scheme'),
                            ('ports/terminal/profiles', '*.terminal'),
                            ('ports/codex/themes', '*.tmTheme')]:
        stale.extend(str(p.relative_to(ROOT)) for p in (ROOT / folder).glob(pattern) if p not in expected)
    if stale:
        raise ValueError('Missing, stale, or unexpected outputs: ' + ', '.join(stale))
    return len(expected)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check outputs without writing')
    args = parser.parse_args()
    try:
        # Validate before writing any output.
        from validate import validate
        validate()
        print(f'{generate(args.check)} generated files {"checked" if args.check else "written"}.')
    except (ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'{error}\n')
